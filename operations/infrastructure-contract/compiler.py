#!/usr/bin/env python3
"""Compile RE8CH infrastructure contracts into deterministic projections."""

from __future__ import annotations

import argparse
import copy
import hashlib
import ipaddress
import json
import os
import sys
from pathlib import Path
from typing import Any

import jsonschema
import yaml


ROOT = Path(__file__).resolve().parents[2]
CONTRACTS = Path(os.environ.get("INFRASTRUCTURE_CONTRACT_DIR", ROOT / "contracts/infrastructure"))
CLUSTER_PATH = CONTRACTS / "cluster.yaml"
NODES_PATH = CONTRACTS / "nodes.yaml"
TARGETS_PATH = CONTRACTS / "targets.yaml"
OBSERVATION_POLICY_PATH = CONTRACTS / "observation-policy.yaml"
OUTPUT_ROOT = Path(os.environ.get("INFRASTRUCTURE_OUTPUT_DIR", ROOT / ".private-infrastructure-output"))
LEGACY_PATH = OUTPUT_ROOT / "compat-nodes.yaml"
CLUSTER_INVENTORY_PATH = OUTPUT_ROOT / "cluster-node-inventory.yaml"
AI_JSON_PATH = OUTPUT_ROOT / "ai-nodes.json"
AI_CONFIG_PATH = OUTPUT_ROOT / "ai-operations-inventory.yaml"
SSH_CONFIG_PATH = OUTPUT_ROOT / "ssh-config"
SCHEMA_VERSION = "operations.re8ch.com/v1alpha1"


class LiteralDumper(yaml.SafeDumper):
    pass


def _represent_string(dumper: yaml.Dumper, value: str):
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|" if "\n" in value else None)


LiteralDumper.add_representer(str, _represent_string)


def load_yaml(path: Path) -> dict[str, Any]:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def dump_yaml(value: Any) -> str:
    return yaml.dump(value, Dumper=LiteralDumper, sort_keys=False, width=140)


def source_digest() -> str:
    digest = hashlib.sha256()
    for path in (CLUSTER_PATH, NODES_PATH, TARGETS_PATH, OBSERVATION_POLICY_PATH):
        digest.update(path.name.encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return "sha256:" + digest.hexdigest()


def generated_header(digest: str) -> str:
    return (
        "# GENERATED by operations/infrastructure-contract/compiler.py; DO NOT EDIT.\n"
        f"# schema-version: {SCHEMA_VERSION}\n"
        f"# source-digest: {digest}\n"
    )


def validate_contracts() -> tuple[dict[str, Any], list[dict[str, Any]], list[dict[str, Any]]]:
    cluster = load_yaml(CLUSTER_PATH)
    node_list = load_yaml(NODES_PATH)
    target_list = load_yaml(TARGETS_PATH)
    pairs = (
        (cluster, "cluster-contract.schema.json", False),
        (node_list, "node-contract.schema.json", True),
        (target_list, "operations-target-contract.schema.json", True),
    )
    for document, schema_name, is_list in pairs:
        schema = json.loads((ROOT / "schemas" / schema_name).read_text(encoding="utf-8"))
        values = document["items"] if is_list else [document]
        for value in values:
            item = value if not is_list else {
                "apiVersion": document["apiVersion"],
                "kind": document["kind"].removesuffix("List"),
                **value,
            }
            jsonschema.validate(item, schema, format_checker=jsonschema.FormatChecker())

    nodes = node_list["items"]
    targets = target_list["items"]
    names = [item["metadata"]["name"] for item in nodes]
    expected_count = cluster["spec"]["expectedNodeCount"]
    if len(names) != expected_count:
        raise ValueError(f"NodeContract count must be {expected_count}, got {len(names)}")
    _unique(nodes, lambda item: item["metadata"]["uid"], "NodeContract UID")
    _unique(nodes, lambda item: item["spec"]["kubernetesName"], "Kubernetes node name")
    for field in ("zeroTierIP", "kubeletInternalIP", "acceleratedIP", "podCIDR"):
        _unique(nodes, lambda item, key=field: item["spec"]["network"].get(key), field)
    _unique(nodes, lambda item: item["spec"]["network"]["fabric"].get("asn"), "fabric ASN")
    target_names = {item["metadata"]["name"] for item in targets}
    if set(names) & target_names:
        raise ValueError("OperationsTargetContract must not duplicate a main-cluster NodeContract")
    for item in nodes:
        net = item["spec"]["network"]
        for key in ("zeroTierIP", "kubeletInternalIP", "acceleratedIP"):
            ipaddress.ip_address(net[key])
        ipaddress.ip_network(net["podCIDR"])
    return cluster, nodes, targets


def _unique(items: list[dict[str, Any]], getter, label: str) -> None:
    seen: dict[Any, str] = {}
    for item in items:
        value = getter(item)
        if value is None:
            continue
        name = item["metadata"]["name"]
        if value in seen:
            raise ValueError(f"duplicate {label} {value!r}: {seen[value]} and {name}")
        seen[value] = name


def compatibility_item_from_node(item: dict[str, Any]) -> dict[str, Any]:
    spec = item["spec"]
    host = spec["host"]
    network = spec["network"]
    kubernetes = spec["kubernetes"]
    cluster = {
        "membership": spec["lifecycle"],
        "roles": spec["roles"],
        "services": spec["services"],
        "labels": kubernetes["gitOpsOwnedLabels"],
        "taints": kubernetes["taints"],
        "parameters": host["parameters"],
        "network": network["legacyNetwork"],
        "fabric": network["fabric"],
    }
    if host.get("storage"):
        cluster["storage"] = host["storage"]
    legacy = {
        "transport": spec["transport"]["type"],
        "address": spec["transport"]["address"],
        "credentialRef": spec["transport"]["credentialRef"],
    }
    if spec["transport"].get("cloud"):
        legacy["cloud"] = spec["transport"]["cloud"]
    legacy.update({"capabilities": spec["capabilities"], "cluster": cluster, "commands": spec["transport"]["commands"]})
    return {"metadata": {"name": item["metadata"]["name"]}, "spec": legacy}


def compatibility_item_from_target(item: dict[str, Any]) -> dict[str, Any]:
    spec = item["spec"]
    legacy = {
        "transport": spec["transport"]["type"],
        "address": spec["transport"]["address"],
        "credentialRef": spec["transport"]["credentialRef"],
        "capabilities": spec["capabilities"],
    }
    if spec["transport"].get("cloud"):
        legacy["cloud"] = spec["transport"]["cloud"]
    if spec.get("legacyCluster"):
        legacy["cluster"] = spec["legacyCluster"]
    legacy["commands"] = spec["transport"]["commands"]
    return {"metadata": {"name": item["metadata"]["name"]}, "spec": legacy}


def render_outputs() -> dict[Path, str]:
    cluster, nodes, targets = validate_contracts()
    digest = source_digest()
    legacy_items = [compatibility_item_from_node(item) for item in nodes]
    legacy_items += [compatibility_item_from_target(item) for item in targets if "compatInventory" in item["spec"]["publishTo"]]
    legacy = {"apiVersion": SCHEMA_VERSION, "kind": "InfrastructureTargetList", "items": legacy_items}

    public_nodes: dict[str, Any] = {}
    fabric_nodes: list[dict[str, Any]] = []
    for item in nodes:
        spec = item["spec"]
        net = spec["network"]
        public_nodes[spec["kubernetesName"]] = {
            "capacityMbps": net["legacyNetwork"]["uplinkMbps"],
            "region": spec["region"],
        }
        fabric_nodes.append({
            "name": spec["kubernetesName"],
            "region": spec["region"],
            "uplinkMbps": net["legacyNetwork"]["uplinkMbps"],
            **net["fabric"],
        })
    values = yaml.safe_dump({"advancedFabric": {"nodes": fabric_nodes}}, sort_keys=False)
    configmap = {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": "cluster-node-inventory",
            "namespace": "flux-system",
            "labels": {"reconcile.fluxcd.io/watch": "Enabled"},
            "annotations": {
                "operations.re8ch.com/generated-by": "infrastructure-contract-compiler",
                "operations.re8ch.com/schema-version": SCHEMA_VERSION,
                "operations.re8ch.com/source-digest": digest,
            },
        },
        "data": {
            "nodes.json": json.dumps(public_nodes, sort_keys=True, separators=(",", ":")),
            "advanced-fabric-values.yaml": values,
        },
    }

    ai_nodes: list[dict[str, Any]] = []
    for item in nodes:
        projection = item["spec"].get("aiOperations")
        if not projection:
            continue
        ai_nodes.append({
            "id": item["metadata"]["name"],
            "target": projection["target"],
            "address": item["spec"]["network"]["zeroTierIP"],
            "roles": projection["roles"],
            "enabled": projection["enabled"],
        })
    for item in targets:
        projection = item["spec"].get("aiOperations")
        if projection:
            ai_nodes.append(copy.deepcopy(projection))
    ai_json = json.dumps(ai_nodes, indent=2, ensure_ascii=False, separators=(",", ": ")) + "\n"
    ssh_config = _render_ssh_config(nodes, targets)
    known_hosts = "\n".join(
        item["spec"]["byoc"]["knownHost"] for item in targets if item["spec"].get("byoc", {}).get("knownHost")
    )
    ai_config = [
        {
            "apiVersion": "v1", "kind": "ConfigMap",
            "metadata": {
                "name": "ai-operations-inventory", "namespace": "ai-operations",
                "annotations": {"operations.re8ch.com/source-digest": digest, "operations.re8ch.com/schema-version": SCHEMA_VERSION},
            },
            "data": {"nodes.json": ai_json},
        },
        {
            "apiVersion": "v1", "kind": "ConfigMap",
            "metadata": {
                "name": "ai-operations-ssh-config", "namespace": "ai-operations",
                "annotations": {"operations.re8ch.com/source-digest": digest, "operations.re8ch.com/schema-version": SCHEMA_VERSION},
            },
            "data": {"byoc-known-hosts": known_hosts + "\n", "ssh-config": ssh_config},
        },
    ]
    return {
        LEGACY_PATH: generated_header(digest) + dump_yaml(legacy),
        CLUSTER_INVENTORY_PATH: generated_header(digest) + dump_yaml(configmap),
        AI_JSON_PATH: ai_json,
        AI_CONFIG_PATH: generated_header(digest) + "---\n".join(dump_yaml(item) for item in ai_config),
        SSH_CONFIG_PATH: ssh_config,
    }


def _render_ssh_config(nodes: list[dict[str, Any]], targets: list[dict[str, Any]]) -> str:
    entries: list[str] = []
    for item in [*nodes, *targets]:
        projection = item["spec"].get("sshConfig")
        if not projection:
            continue
        aliases = " ".join(projection["aliases"])
        entries.extend([f"Host {aliases}", f"  HostName {projection['hostName']}", f"  User {projection['user']}"])
        if projection.get("proxyJump"):
            entries.append(f"  ProxyJump {projection['proxyJump']}")
        entries.append("")
    entries.extend([
        "Host *",
        "  BatchMode yes",
        "  IdentitiesOnly yes",
        "  IdentityFile /etc/re8ch-ai-operations/id_ed25519",
        "  StrictHostKeyChecking accept-new",
        "  UserKnownHostsFile /var/lib/re8ch-ai-operations/known_hosts",
        "  ConnectTimeout 10",
        "  ServerAliveInterval 20",
        "  ServerAliveCountMax 3",
    ])
    return "\n".join(entries).rstrip() + "\n"


def write_or_check(check: bool) -> None:
    outputs = render_outputs()
    stale = []
    for path, expected in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    if stale:
        raise SystemExit("stale generated infrastructure projections: " + ", ".join(stale))


def observe_diff(observed_path: str) -> int:
    cluster, nodes, _ = validate_contracts()
    raw = sys.stdin.read() if observed_path == "-" else Path(observed_path).read_text(encoding="utf-8")
    observed = json.loads(raw)
    actual = {item["metadata"]["name"]: item for item in observed["items"]}
    expected = {item["spec"]["kubernetesName"]: item for item in nodes}
    drift: list[dict[str, Any]] = []
    for name in sorted(set(expected) - set(actual)):
        drift.append({"severity": "immediate", "type": "missing-node", "contractRef": expected[name]["metadata"]["uid"]})
    for name in sorted(set(actual) - set(expected)):
        opaque = hashlib.sha256((cluster["metadata"]["uid"] + ":" + name).encode()).hexdigest()[:16]
        drift.append({"severity": "immediate", "type": "unexpected-node", "contractRef": "unmanaged-" + opaque})
    facts = []
    for name in sorted(set(expected) & set(actual)):
        contract = expected[name]
        live = actual[name]
        spec = contract["spec"]
        contract_ref = contract["metadata"]["uid"]
        addresses = {item["type"]: item["address"] for item in live.get("status", {}).get("addresses", [])}
        if live["metadata"].get("uid") != spec["observation"]["nodeUID"]:
            drift.append({"severity": "immediate", "type": "node-uid", "contractRef": contract_ref})
        if addresses.get("InternalIP") != spec["network"]["kubeletInternalIP"]:
            drift.append({"severity": "persistent", "type": "internal-ip", "contractRef": contract_ref})
        labels = live["metadata"].get("labels", {})
        for key, value in spec["kubernetes"]["gitOpsOwnedLabels"].items():
            if labels.get(key) != value:
                drift.append({"severity": "persistent", "type": "label", "contractRef": contract_ref, "fieldRef": hashlib.sha256(key.encode()).hexdigest()[:12]})
        expected_taints = sorted(spec["kubernetes"]["taints"], key=lambda value: (value["key"], value.get("effect", ""), value.get("value", "")))
        actual_taints = sorted(live.get("spec", {}).get("taints", []), key=lambda value: (value["key"], value.get("effect", ""), value.get("value", "")))
        actual_taints = [{key: value[key] for key in ("key", "value", "effect") if key in value} for value in actual_taints]
        if expected_taints != actual_taints:
            drift.append({"severity": "immediate", "type": "taints", "contractRef": contract_ref})
        conditions = {item["type"]: item["status"] for item in live.get("status", {}).get("conditions", [])}
        facts.append({"contractRef": contract_ref, "ready": conditions.get("Ready"), "conditions": conditions})
    result = {"schemaVersion": "v1alpha1", "clusterRef": cluster["metadata"]["uid"], "expectedNodeCount": cluster["spec"]["expectedNodeCount"], "observedNodeCount": len(actual), "drift": drift, "statusFacts": facts}
    print(json.dumps(result, indent=2, sort_keys=True))
    return 2 if drift else 0


def verify_encrypted() -> None:
    paths = (
        ROOT / "clusters/re8ch/secrets/infrastructure-contracts.sops.yaml",
        ROOT / "clusters/re8ch/secrets/cluster-node-inventory.sops.yaml",
        ROOT / "clusters/re8ch/secrets/ai-operations-inventory.sops.yaml",
    )
    digests: set[str] = set()
    for path in paths:
        documents = [item for item in yaml.safe_load_all(path.read_text(encoding="utf-8")) if item]
        if not documents:
            raise ValueError(f"empty encrypted projection: {path}")
        for document in documents:
            if document.get("kind") != "Secret" or "sops" not in document:
                raise ValueError(f"projection is not a SOPS Secret: {path}")
            payload = document.get("stringData") or document.get("data") or {}
            if not payload or not all(isinstance(value, str) and value.startswith("ENC[") for value in payload.values()):
                raise ValueError(f"unencrypted Secret payload in {path}")
            digest = document.get("metadata", {}).get("annotations", {}).get("operations.re8ch.com/source-digest")
            if not digest:
                raise ValueError(f"missing source digest on {path}")
            digests.add(digest)
    if len(digests) != 1:
        raise ValueError(f"encrypted projections have different source digests: {sorted(digests)}")
    forbidden = (
        ROOT / "inventory/nodes.yaml",
        ROOT / "clusters/re8ch/components/cluster-inventory/configmap.yaml",
        ROOT / "clusters/re8ch/components/ai-operations/nodes.json",
        ROOT / "clusters/re8ch/components/ai-operations/ssh_config.template",
    )
    leaked = [path.relative_to(ROOT).as_posix() for path in forbidden if path.exists()]
    if leaked:
        raise ValueError("plaintext infrastructure projections are forbidden: " + ", ".join(leaked))


def main() -> None:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("render")
    sub.add_parser("check")
    sub.add_parser("verify-encrypted")
    observe = sub.add_parser("observe-diff")
    observe.add_argument("observed", help="kubectl NodeList JSON path, or - for stdin")
    args = parser.parse_args()
    if args.command == "render":
        write_or_check(False)
    elif args.command == "check":
        write_or_check(True)
    elif args.command == "verify-encrypted":
        verify_encrypted()
    else:
        raise SystemExit(observe_diff(args.observed))


if __name__ == "__main__":
    main()
