#!/usr/bin/env python3
"""One-shot reviewed migration for deterministic automation PR factors."""

from __future__ import annotations

import argparse
import concurrent.futures
import datetime as dt
import json
import os
import re
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any


API = "https://api.github.com"
GRAPHQL = f"{API}/graphql"
MARKER = "transaction-factor-backfill"


def slug_title(key: str) -> str:
    kind, repository, stream = (key.split(":", 2) + [""])[:3]
    if kind == "pull-request-context":
        return f"Track {repository}#{stream}"
    if kind == "domain-oci-promotion":
        return f"Track domain OCI promotions for {repository}"
    return f"Track {stream} dependency updates for {repository}"


def factor_body(key: str, parent: str, count: int) -> str:
    return f"""## Outcome
Own lifecycle and acceptance for the open automation PR stream `{key}`.

## Context
- Parent Issue: {parent}
- Aggregation key: `{key}`
- Planned PR count: {count}
- Root declaration: child migration factor

## Acceptance
- [ ] Every retained PR in this stream has a native closing relationship
- [ ] Each PR remains independently reviewable and open until its own checks pass
- [ ] New revisions remain immutable and are tested once

## Evidence
Generated by the reviewed bulk backfill migration. This Issue does not authorize merging or closing its PRs.

<!-- {MARKER}:{key} -->
"""


def append_closing(body: str | None, factor: str, key: str) -> str:
    body = body or ""
    marker = f"<!-- {MARKER}:{key} -->"
    if marker in body:
        return body
    body = body.rstrip()
    suffix = f"{marker}\nCloses {factor}"
    return f"{body}\n\n{suffix}\n" if body else f"{suffix}\n"


class GitHub:
    def __init__(self, token: str):
        self.token = token

    def request(self, url: str, method: str = "GET", data: dict[str, Any] | None = None) -> Any:
        for attempt in range(4):
            request = urllib.request.Request(
                url if url.startswith("http") else f"{API}{url}",
                method=method,
                data=(json.dumps(data).encode() if data is not None else None),
                headers={
                    "Authorization": f"Bearer {self.token}",
                    "Accept": "application/vnd.github+json",
                    "Content-Type": "application/json",
                    "User-Agent": "re8ch-bulk-factor-backfill",
                    "X-GitHub-Api-Version": "2026-03-10",
                },
            )
            try:
                with urllib.request.urlopen(request, timeout=45) as response:
                    return json.load(response) if response.length != 0 else None
            except urllib.error.HTTPError as error:
                detail = error.read().decode(errors="replace")
                if error.code < 500 or attempt == 3:
                    raise RuntimeError(f"{method} {url}: HTTP {error.code}: {detail}") from error
            except (urllib.error.URLError, ConnectionError, OSError):
                if attempt == 3:
                    raise
            time.sleep(1 + attempt)
        raise AssertionError("unreachable")

    def graphql(self, query: str, variables: dict[str, Any]) -> dict[str, Any]:
        payload = self.request(GRAPHQL, "POST", {"query": query, "variables": variables})
        if payload.get("errors"):
            raise RuntimeError(json.dumps(payload["errors"], sort_keys=True))
        return payload["data"]


PROJECT_QUERY = """
query($owner:String!,$number:Int!){organization(login:$owner){projectV2(number:$number){id fields(first:50){nodes{... on ProjectV2Field{id name dataType} ... on ProjectV2SingleSelectField{id name options{id name}}}}}}}
"""
REPO_QUERY = """
query($owner:String!,$repo:String!){repository(owner:$owner,name:$repo){issueTypes(first:20){nodes{id name}}}}
"""
UPDATE_TYPE = "mutation($id:ID!,$type:ID!){updateIssue(input:{id:$id,issueTypeId:$type}){issue{id}}}"
ADD_ITEM = "mutation($project:ID!,$content:ID!){addProjectV2ItemById(input:{projectId:$project,contentId:$content}){item{id}}}"
UPDATE_FIELD = "mutation($project:ID!,$item:ID!,$field:ID!,$value:ProjectV2FieldValue!){updateProjectV2ItemFieldValue(input:{projectId:$project,itemId:$item,fieldId:$field,value:$value}){projectV2Item{id}}}"
VERIFY_PR = """
query($owner:String!,$repo:String!,$number:Int!){repository(owner:$owner,name:$repo){pullRequest(number:$number){state closingIssuesReferences(first:20){nodes{url}}}}}
"""


def project_context(client: GitHub) -> tuple[str, dict[str, Any]]:
    project = client.graphql(PROJECT_QUERY, {"owner": "re8ch", "number": 2})["organization"]["projectV2"]
    return project["id"], {node["name"]: node for node in project["fields"]["nodes"] if node.get("name")}


def set_project_fields(client: GitHub, project_id: str, fields: dict[str, Any], item_id: str, work_type: str = "Dependency") -> None:
    today = dt.date.today()
    values = {
        "Status": "Todo", "Lifecycle": "Ready", "Work Type": work_type,
        "Context Status": "Ready", "Start Date": today.isoformat(),
        "Target Date": (today + dt.timedelta(days=30)).isoformat(),
    }
    for name, value in values.items():
        field = fields[name]
        if "options" in field:
            option = next(option["id"] for option in field["options"] if option["name"] == value)
            encoded = {"singleSelectOptionId": option}
        else:
            encoded = {"date": value}
        client.graphql(UPDATE_FIELD, {"project": project_id, "item": item_id, "field": field["id"], "value": encoded})


def ensure_parent(client: GitHub, factor: dict[str, Any], parent: str) -> None:
    parent_repository, parent_number = parent.rsplit("#", 1)
    sub_issues = client.request(f"/repos/{parent_repository}/issues/{parent_number}/sub_issues?per_page=100")
    if any(issue["id"] == factor["id"] for issue in sub_issues):
        return
    client.request(
        f"/repos/{parent_repository}/issues/{parent_number}/sub_issues",
        "POST",
        {"sub_issue_id": factor["id"]},
    )


def create_factor(client: GitHub, group: dict[str, Any], project_id: str, fields: dict[str, Any], parent: str) -> dict[str, Any]:
    metadata = client.request(f"/repos/{group['repository']}")
    target_repository = metadata["full_name"]
    repository = group.get("factorRepository") or (
        target_repository if metadata["has_issues"] else "re8ch/service-backend"
    )
    owner, repo = repository.split("/", 1)
    marker = f"<!-- {MARKER}:{group['key']} -->"
    existing = client.request(f"/repos/{repository}/issues?state=open&per_page=100")
    for candidate in existing:
        if "pull_request" not in candidate and marker in (candidate.get("body") or ""):
            factor = {"repository": repository, "number": candidate["number"], "url": candidate["html_url"], "id": candidate["id"]}
            ensure_parent(client, factor, parent)
            return factor
    issue = client.request(f"/repos/{repository}/issues", "POST", {
        "title": group.get("title") or slug_title(group["key"]),
        "body": factor_body(group["key"], parent, len(group["pullRequests"])) + (
            f"\nFactor repository fallback: `{target_repository}` has Issues disabled.\n"
            if repository != target_repository else ""
        ),
    })
    types = client.graphql(REPO_QUERY, {"owner": owner, "repo": repo})["repository"]["issueTypes"]["nodes"]
    task = next(node["id"] for node in types if node["name"] == "Task")
    client.graphql(UPDATE_TYPE, {"id": issue["node_id"], "type": task})
    item = client.graphql(ADD_ITEM, {"project": project_id, "content": issue["node_id"]})["addProjectV2ItemById"]["item"]
    set_project_fields(client, project_id, fields, item["id"], group.get("workType", "Dependency"))
    factor = {"repository": repository, "number": issue["number"], "url": issue["html_url"], "id": issue["id"]}
    ensure_parent(client, factor, parent)
    return factor


def link_pr(client: GitHub, group: dict[str, Any], pr: dict[str, Any], factor: dict[str, Any]) -> dict[str, Any]:
    original_repository = pr["repository"]
    repository = client.request(f"/repos/{original_repository}")["full_name"]
    number = pr["number"]
    before = client.request(f"/repos/{repository}/pulls/{number}")
    if before["state"] != "open" or before.get("merged"):
        return {"repository": repository, "number": number, "status": "skipped", "reason": "PR is no longer open"}
    new_body = append_closing(before.get("body"), factor["url"], group["key"])
    client.request(f"/repos/{repository}/pulls/{number}", "PATCH", {"body": new_body})
    canonical = client.request(f"/repos/{repository}")["full_name"]
    owner, repo = canonical.split("/", 1)
    for attempt in range(6):
        readback = client.graphql(VERIFY_PR, {"owner": owner, "repo": repo, "number": number})["repository"]["pullRequest"]
        urls = [node["url"] for node in readback["closingIssuesReferences"]["nodes"]]
        if readback["state"] == "OPEN" and factor["url"] in urls:
            break
        if attempt < 5:
            time.sleep(2)
    else:
        raise RuntimeError(f"native closing relationship missing after delayed readback: {repository}#{number}")
    return {"repository": repository, "number": number, "status": "succeeded", "factor": factor["url"]}


def apply(plan: dict[str, Any], token: str, workers: int) -> dict[str, Any]:
    client = GitHub(token)
    project_id, fields = project_context(client)
    results: list[dict[str, Any]] = []
    factors = []
    for group in plan["groups"]:
        try:
            factor = create_factor(client, group, project_id, fields, plan["parentIssue"])
            factors.append({**factor, "key": group["key"]})
        except Exception as error:
            for pr in group["pullRequests"]:
                results.append({**pr, "status": "failed", "reason": f"factor creation failed: {error}"})
            continue
        with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as executor:
            futures = {executor.submit(link_pr, client, group, pr, factor): pr for pr in group["pullRequests"]}
            for future in concurrent.futures.as_completed(futures):
                pr = futures[future]
                try:
                    results.append(future.result())
                except Exception as error:
                    results.append({**pr, "status": "failed", "reason": str(error)})
    counts = {state: sum(row["status"] == state for row in results) for state in ("succeeded", "failed", "skipped")}
    return {"kind": "AutomationFactorBulkBackfillResult", "factors": factors, "transactions": sorted(results, key=lambda row: (row["repository"], row["number"])), "summary": {"attempted": len(results), **counts}}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--plan", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--workers", type=int, default=6)
    args = parser.parse_args()
    plan = json.loads(args.plan.read_text())
    if not args.apply:
        print(json.dumps({"groups": len(plan["groups"]), "pullRequests": sum(len(group["pullRequests"]) for group in plan["groups"])}, indent=2))
        return 0
    result = apply(plan, os.environ["GH_TOKEN"], args.workers)
    args.output.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result["summary"], indent=2))
    return int(result["summary"]["failed"] > 0)


if __name__ == "__main__":
    raise SystemExit(main())
