#!/usr/bin/env python3
"""Partition main-domain Flux inventories into bounded SSA releases.

Secret payloads, platform-owned RBAC, Flux lifecycle references and HelmRelease
objects remain explicit bootstrap gaps. Namespaced workloads and non-RBAC
cluster bootstrap objects use separate exact contracts; cluster bootstrap never
prunes and receives no create, delete, bind or escalate authorization.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import shutil
from collections import Counter, defaultdict
from pathlib import Path

import yaml

# LibYAML keeps SafeLoader constructors; pure Python remains a supported fallback.
YAML_SAFE_LOADER = getattr(yaml, "CSafeLoader", yaml.SafeLoader)

from operation_materialize import state_configmap_name

ROOT = Path(__file__).resolve().parents[2]
DOMAINS = ("data-storage", "commerce-billing", "delivery-products", "operations-ui", "tenant-runtime")
AUTONOMOUS = {"networking", "identity-access", "agent-runtime", "observability-metering"}
DEFERRED_SSA: set[str] = {
    # Shared database-domain Gateway attachments remain Flux-owned platform
    # guardrails. The retired payments publisher cannot create missing routes,
    # and product release authority must not own shared edge/database routing.
    "gateway.networking.k8s.io/HTTPRoute/payments/re8ch-payment-registry-db-ro",
    "gateway.networking.k8s.io/HTTPRoute/payments/re8ch-payment-registry-db-rw",
}
OUTPUT = ROOT / "operations/releases/main-domain-ssa"
CONTRACTS = ROOT / "contracts/releases/main-domain"
LEGACY = ROOT / "clusters/re8ch/domains/main-legacy"
RBAC = ROOT / "clusters/re8ch/components/ops/github-actions-main-domain-executor-rbac.yaml"
AUTHORITY = ROOT / "operations/releases/static-domain-authority.yaml"
CLUSTER_KINDS = {
    "APIService", "ClusterRole", "ClusterRoleBinding", "CustomResourceDefinition", "Namespace",
    "Node", "PersistentVolume", "StorageClass", "ValidatingWebhookConfiguration", "MutatingWebhookConfiguration",
    "ValidatingAdmissionPolicy", "ValidatingAdmissionPolicyBinding", "ClusterPolicy",
    "NodeProfile", "PlacementClass", "SchedulerProfile", "TenantNamespace",
}
RBAC_KINDS = {"Role", "RoleBinding", "ClusterRole", "ClusterRoleBinding"}
CLUSTER_EXECUTABLE = CLUSTER_KINDS - RBAC_KINDS
CLUSTER_PARTITION = "cluster-bootstrap"
CLUSTER_STATE_NAMESPACE = "ops"
FLUX_KINDS = {"HelmRelease", "Kustomization", "GitRepository", "HelmRepository", "OCIRepository", "HelmChart"}
PLURALS = {
    "ServiceAccount": "serviceaccounts", "Service": "services", "ConfigMap": "configmaps",
    "PersistentVolumeClaim": "persistentvolumeclaims", "Deployment": "deployments",
    "StatefulSet": "statefulsets", "DaemonSet": "daemonsets", "Job": "jobs", "CronJob": "cronjobs",
    "HorizontalPodAutoscaler": "horizontalpodautoscalers", "PodDisruptionBudget": "poddisruptionbudgets",
    "NetworkPolicy": "networkpolicies", "Ingress": "ingresses", "EndpointSlice": "endpointslices",
    "HTTPRoute": "httproutes", "CiliumNetworkPolicy": "ciliumnetworkpolicies",
    "MCPServer": "mcpservers", "Namespace": "namespaces", "Node": "nodes",
    "PersistentVolume": "persistentvolumes", "StorageClass": "storageclasses",
    "CustomResourceDefinition": "customresourcedefinitions", "ClusterPolicy": "clusterpolicies",
    "NodeProfile": "nodeprofiles", "PlacementClass": "placementclasses", "SchedulerProfile": "schedulerprofiles",
    "ValidatingAdmissionPolicy": "validatingadmissionpolicies", "ValidatingAdmissionPolicyBinding": "validatingadmissionpolicybindings",
}
def execution_profiles() -> dict[str, dict]:
    authority = yaml.load(AUTHORITY.read_text(), Loader=YAML_SAFE_LOADER)
    profiles = authority["spec"]["domains"]
    missing = set(DOMAINS) - set(profiles)
    if missing:
        raise ValueError(f"missing static domain authority profiles: {sorted(missing)}")
    return {domain: profiles[domain]["execution"] for domain in DOMAINS}


def docs(path: Path) -> list[dict]:
    return [item for item in yaml.load_all(path.read_text(), Loader=YAML_SAFE_LOADER) if isinstance(item, dict)]


def group(api_version: str) -> str:
    return api_version.split("/", 1)[0] if "/" in api_version else "core"


def identity(item: dict) -> str:
    meta = item["metadata"]
    return f'{group(item["apiVersion"])}/{item["kind"]}/{meta.get("namespace", "_")}/{meta["name"]}'


def canonical(value: object) -> bytes:
    return (json.dumps(value, sort_keys=True, separators=(",", ":")) + "\n").encode()


def digest(value: object) -> str:
    return "sha256:" + hashlib.sha256(canonical(value)).hexdigest()


def dump_all(items: list[dict]) -> str:
    return "# Generated by operations/releases/compile_main_domain_ssa.py; do not edit.\n" + yaml.safe_dump_all(
        items, sort_keys=False, explicit_start=True)


def release_name(domain: str, namespace: str) -> str:
    return f"main-{domain}-{namespace}"[:63].rstrip("-")


def has_mutable_image(value: object) -> bool:
    if isinstance(value, dict):
        return any((key == "image" and isinstance(child, str) and "@sha256:" not in child)
                   or has_mutable_image(child) for key, child in value.items())
    if isinstance(value, list):
        return any(has_mutable_image(child) for child in value)
    return False


def role_rules(items: list[dict], state_name: str | None, *, allow_delete: bool = True) -> list[dict]:
    rules: dict[tuple[str, str], set[str]] = defaultdict(set)
    for item in items:
        plural = PLURALS.get(item["kind"])
        if not plural:
            raise ValueError(f'no RBAC plural mapping for {item["apiVersion"]}/{item["kind"]}')
        rules[(group(item["apiVersion"]), plural)].add(item["metadata"]["name"])
    if state_name:
        rules[("core", "configmaps")].add(state_name)
    result = []
    for (api_group, resource), names in sorted(rules.items()):
        verbs = ["get", "patch", "update"] + (["delete"] if allow_delete else [])
        result.append({
            "apiGroups": ["" if api_group == "core" else api_group],
            "resources": [resource],
            "resourceNames": sorted(names),
            "verbs": verbs,
        })
    return result


def legacy_reason(item: dict, domain: str | None = None) -> str | None:
    """Return the remaining capability gap, never an obsolete Flux ownership hint."""
    meta = item.get("metadata", {})
    if meta.get("labels", {}).get("delivery.re8ch.com/retention") == "retained-data":
        return "retained-data-no-automatic-mutation"
    if identity(item) in DEFERRED_SSA:
        return "explicitly-deferred"
    if item["kind"] in RBAC_KINDS:
        return "platform-owned-rbac-bootstrap"
    if item["kind"] == "Secret":
        return "approved-secret-injection-required"
    if item["kind"] == "HelmRelease":
        return "cloud-helm-rendering-required"
    if item["kind"] in FLUX_KINDS:
        return "replace-flux-lifecycle-reference"
    if not meta.get("namespace") or item["kind"] in CLUSTER_KINDS:
        if item["kind"] not in CLUSTER_EXECUTABLE:
            return "cluster-scoped-executor-profile-required"
        if domain and execution_profiles()[domain]["repository"] != "re8ch/service-backend":
            return "external-authority-cluster-bootstrap-required"
        return None
    if meta["namespace"] == "flux-system":
        return "bootstrap-namespace-executor-profile-required"
    if has_mutable_image(item):
        return "immutable-image-digest-required"
    return None


def canonical_admission_defaults(item: dict) -> None:
    """Make API-defaulted atomic match constraints explicit without changing policy."""
    if item.get("apiVersion") == "kyverno.io/v1" and item.get("kind") == "ClusterPolicy":
        spec = item["spec"]
        spec.setdefault("admission", True)
        spec.setdefault("emitWarning", False)
        for rule in spec.get("rules", []):
            rule.setdefault("skipBackgroundRequests", True)
            if "validate" in rule:
                rule["validate"].setdefault("allowExistingViolations", True)
        return
    if item.get("apiVersion") != "admissionregistration.k8s.io/v1" or item.get("kind") != "ValidatingAdmissionPolicy":
        return
    constraints = item["spec"]["matchConstraints"]
    constraints.setdefault("matchPolicy", "Equivalent")
    constraints.setdefault("namespaceSelector", {})
    constraints.setdefault("objectSelector", {})
    for key in ("resourceRules", "excludeResourceRules"):
        for rule in constraints.get(key, []):
            rule.setdefault("scope", "*")


def compile_outputs() -> dict[Path, str]:
    profiles = execution_profiles()
    retired = yaml.load(AUTHORITY.read_text(), Loader=YAML_SAFE_LOADER)["spec"].get("retiredReleases", {})
    releases: dict[tuple[str, str], list[dict]] = defaultdict(list)
    legacy: dict[str, list[dict]] = defaultdict(list)
    seen: dict[str, str] = {}
    remaining: list[dict] = []
    omissions: list[dict] = []
    retained_rbac_namespaces: set[tuple[str, str]] = set()
    for domain in DOMAINS:
        for item in docs(ROOT / f"clusters/re8ch/domains/{domain}/resources.yaml"):
            ident = identity(item)
            if ident in seen:
                raise ValueError(f"duplicate identity across {seen[ident]} and {domain}: {ident}")
            seen[ident] = domain
            meta = item.get("metadata", {})
            namespace = meta.get("namespace")
            reason = legacy_reason(item, domain)
            if reason:
                legacy[domain].append(item)
                remaining.append({"domain": domain, "identity": ident, "reason": reason})
                if reason == "platform-owned-rbac-bootstrap" and namespace:
                    retained_rbac_namespaces.add((domain, namespace))
            else:
                if item["kind"] == "Node" and "spec" in item:
                    for field in sorted(item.pop("spec")):
                        omissions.append({"domain": domain, "identity": ident, "field": f"spec.{field}",
                                          "authority": "existing-runtime-node-authority",
                                          "reason": "cloud-adoption-manages-static-metadata-only"})
                canonical_admission_defaults(item)
                # Kubernetes stores byte fields as canonical, unwrapped base64.
                # Wrapped YAML scalars otherwise conflict under SSA despite equal bytes.
                if item["kind"] == "ConfigMap" and item.get("binaryData"):
                    item["binaryData"] = {
                        key: base64.b64encode(base64.b64decode("".join(value.split()), validate=True)).decode()
                        for key, value in item["binaryData"].items()
                    }
                releases[(domain, namespace or CLUSTER_PARTITION)].append(item)

    revision = "github-main-reviewed"
    files: dict[Path, str] = {}
    rbac_docs: list[dict] = []
    for (domain, partition), items in sorted(releases.items()):
        cluster = partition == CLUSTER_PARTITION
        namespace = CLUSTER_STATE_NAMESPACE if cluster else partition
        profile = profiles[domain]
        prune = not cluster and (domain, namespace) not in retained_rbac_namespaces
        items.sort(key=identity)
        name = release_name(domain, partition)
        package = OUTPUT / name
        files[package / "resources.yaml"] = dump_all(items)
        files[package / "kustomization.yaml"] = yaml.safe_dump({
            "apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": ["resources.yaml"]
        }, sort_keys=False)
        inventory = sorted(identity(item) for item in items)
        contract = {
            "apiVersion": "delivery.re8ch.com/v1alpha1", "kind": "ReleaseContract", "metadata": {"name": name},
            "spec": {
                "authorityDomain": domain,
                "target": {"cluster": "re8ch", "namespace": namespace},
                "source": {"renderer": "kustomize", "revision": revision, "repository": "re8ch/service-backend",
                           "path": str(package.relative_to(ROOT))},
                "provenance": {"repository": profile["repository"], "workflow": profile["workflow"],
                               "ref": "refs/heads/main", "environment": profile["protectedEnvironment"],
                               "audience": profile["audience"],
                               "signer": f'https://github.com/{profile["repository"]}/{profile["workflow"]}@refs/heads/main',
                               "issuer": "https://token.actions.githubusercontent.com"},
                "authorization": {"fieldManager": f"re8ch-release/{name}",
                                  "resources": sorted({f'{group(x["apiVersion"])}/{x["kind"]}' for x in items}),
                                  "objectNames": sorted({x["metadata"]["name"] for x in items}),
                                  "allowClusterScoped": cluster},
                "inventory": {"digest": digest(inventory)},
                "lifecycle": {"prune": prune, "healthTimeoutSeconds": 300,
                              "protectedKinds": sorted(CLUSTER_EXECUTABLE | {"PersistentVolumeClaim"}) if cluster else
                                                ["Namespace", "CustomResourceDefinition", "PersistentVolume", "PersistentVolumeClaim", "StorageClass"],
                              "deletionAllowlist": [] if not prune else [x for x in inventory if "/PersistentVolumeClaim/" not in x]},
            },
        }
        reviewed_takeovers = {
            "main-data-storage-ops": "apps/Deployment/ops/cloudbeaver",
            "main-tenant-runtime-scheduling-system": "apps/Deployment/scheduling-system/penrose-controller",
        }
        if name in reviewed_takeovers:
            contract["spec"]["authorization"]["forceConflictObjects"] = [reviewed_takeovers[name]]
        if cluster:
            contract["spec"]["authorization"]["requireExisting"] = True
        files[CONTRACTS / f"{name}.yaml"] = yaml.safe_dump(contract, sort_keys=False)
        state_name = state_configmap_name(name)
        namespaced_rules = role_rules([] if cluster else items, state_name, allow_delete=prune)
        if name in retired:
            for rule in namespaced_rules:
                rule["verbs"] = ["get"]
        rbac_docs.extend([
            {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": state_name, "namespace": namespace,
                "annotations": {"kustomize.toolkit.fluxcd.io/ssa": "Merge"},
                "labels": {"delivery.re8ch.com/state": "accepted", "delivery.re8ch.com/cohort": "main-domain",
                           "delivery.re8ch.com/authority-domain": domain}}},
            {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "Role",
             "metadata": {"name": name, "namespace": namespace,
                          "labels": {"delivery.re8ch.com/rbac-profile": domain}},
             "rules": namespaced_rules},
            {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding",
             "metadata": {"name": name, "namespace": namespace,
                          "labels": {"delivery.re8ch.com/rbac-profile": domain}},
             "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "Role", "name": name},
             "subjects": [{"apiGroup": "rbac.authorization.k8s.io", "kind": "Group",
                           "name": profile["kubernetesGroup"]}]},
        ])
        if cluster:
            rbac_docs.extend([
                {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "ClusterRole",
                 "metadata": {"name": name, "labels": {"delivery.re8ch.com/rbac-profile": domain}},
                 "rules": role_rules(items, None, allow_delete=False)},
                {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "ClusterRoleBinding",
                 "metadata": {"name": name, "labels": {"delivery.re8ch.com/rbac-profile": domain}},
                 "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "ClusterRole", "name": name},
                 "subjects": [{"apiGroup": "rbac.authorization.k8s.io", "kind": "Group", "name": profile["kubernetesGroup"]}]},
            ])
    for domain, items in sorted(legacy.items()):
        items.sort(key=identity)
        files[LEGACY / domain / "resources.yaml"] = dump_all(items)
        files[LEGACY / domain / "kustomization.yaml"] = yaml.safe_dump({
            "apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": ["resources.yaml"]
        }, sort_keys=False)
    files[RBAC] = dump_all(rbac_docs)
    manifest = {
        "apiVersion": "delivery.re8ch.com/main-domain-cohort/v1alpha1", "kind": "MainDomainSSACohort",
        "autonomousDomainsExcluded": sorted(AUTONOMOUS), "sourceDomains": list(DOMAINS),
        "releaseCount": len(releases), "objectCount": sum(map(len, releases.values())),
        "legacyObjectCount": sum(map(len, legacy.values())),
        "deferredSSAObjects": sorted(DEFERRED_SSA),
        "remainingCapabilities": dict(sorted(Counter(item["reason"] for item in remaining).items())),
        "remainingObjects": sorted(remaining, key=lambda item: (item["domain"], item["identity"])),
        "omissions": sorted(omissions, key=lambda item: (item["identity"], item["field"])),
        "executionProfiles": [{"domain": domain, "repository": profiles[domain]["repository"],
                               "workflow": profiles[domain]["workflow"],
                               "protectedEnvironment": profiles[domain]["protectedEnvironment"],
                               "audience": profiles[domain]["audience"],
                               "kubernetesGroup": profiles[domain]["kubernetesGroup"]}
                              for domain in DOMAINS],
        "legacyShards": [{"domain": domain, "objects": len(items)} for domain, items in sorted(legacy.items())],
        "releases": [{"name": release_name(d, n), "domain": d, "namespace": CLUSTER_STATE_NAMESPACE if n == CLUSTER_PARTITION else n,
                      "scope": "cluster-bootstrap" if n == CLUSTER_PARTITION else "namespaced", "objects": len(items)}
                     for (d, n), items in sorted(releases.items())],
    }
    files[OUTPUT / "cohort.yaml"] = yaml.safe_dump(manifest, sort_keys=False)
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = compile_outputs()
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in expected.items()
                 if not path.is_file() or path.read_text() != content]
        if stale:
            raise SystemExit("stale main-domain SSA outputs:\n" + "\n".join(stale))
        return 0
    for directory in (OUTPUT, CONTRACTS, LEGACY):
        if directory.exists():
            shutil.rmtree(directory)
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
