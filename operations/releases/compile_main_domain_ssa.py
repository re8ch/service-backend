#!/usr/bin/env python3
"""Partition main-domain Flux inventories into bounded SSA releases.

Secret payloads, cluster-scoped resources, Flux source/lifecycle objects and
HelmRelease objects remain in the temporary main-legacy reconciliation domain.
Everything else is split by owning domain and namespace so every executor
identity can be expressed as an exact namespaced Role.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from collections import defaultdict
from pathlib import Path

import yaml

from operation_materialize import state_configmap_name

ROOT = Path(__file__).resolve().parents[2]
DOMAINS = ("data-storage", "commerce-billing", "delivery-products", "operations-ui", "tenant-runtime")
AUTONOMOUS = {"networking", "identity-access", "agent-runtime", "observability-metering"}
OUTPUT = ROOT / "operations/releases/main-domain-ssa"
CONTRACTS = ROOT / "contracts/releases/main-domain"
LEGACY = ROOT / "clusters/re8ch/domains/main-legacy"
RBAC = ROOT / "clusters/re8ch/components/ops/github-actions-main-domain-executor-rbac.yaml"
CLUSTER_KINDS = {
    "APIService", "ClusterRole", "ClusterRoleBinding", "CustomResourceDefinition", "Namespace",
    "Node", "PersistentVolume", "StorageClass", "ValidatingWebhookConfiguration", "MutatingWebhookConfiguration",
}
FLUX_KINDS = {"HelmRelease", "Kustomization", "GitRepository", "HelmRepository", "OCIRepository", "HelmChart"}
PLURALS = {
    "ServiceAccount": "serviceaccounts", "Service": "services", "ConfigMap": "configmaps",
    "PersistentVolumeClaim": "persistentvolumeclaims", "Deployment": "deployments",
    "StatefulSet": "statefulsets", "DaemonSet": "daemonsets", "Job": "jobs", "CronJob": "cronjobs",
    "HorizontalPodAutoscaler": "horizontalpodautoscalers", "PodDisruptionBudget": "poddisruptionbudgets",
    "NetworkPolicy": "networkpolicies", "Ingress": "ingresses", "EndpointSlice": "endpointslices",
    "HTTPRoute": "httproutes", "CiliumNetworkPolicy": "ciliumnetworkpolicies",
    "Role": "roles", "RoleBinding": "rolebindings", "MCPServer": "mcpservers",
}
AUDIENCE = "https://kube-api.re8ch.com/release-executor-main-domain"
WORKFLOW = ".github/workflows/main-domain-release.yml"
ENVIRONMENT = "release-main-domain"


def docs(path: Path) -> list[dict]:
    return [item for item in yaml.safe_load_all(path.read_text()) if isinstance(item, dict)]


def group(api_version: str) -> str:
    return api_version.split("/", 1)[0] if "/" in api_version else "core"


def identity(item: dict) -> str:
    meta = item["metadata"]
    return f'{group(item["apiVersion"])}/{item["kind"]}/{meta.get("namespace", "_")}/{meta["name"]}'


def canonical(value: object) -> bytes:
    return (json.dumps(value, sort_keys=True, separators=(",", ":")) + "\n").encode()


def digest(value: object) -> str:
    return "sha256:" + hashlib.sha256(canonical(value)).hexdigest()


def dump_all(items: list[dict]) -> str:
    return "# Generated by operations/releases/compile_main_domain_ssa.py; do not edit.\n" + yaml.safe_dump_all(
        items, sort_keys=False, explicit_start=True)


def release_name(domain: str, namespace: str) -> str:
    return f"main-{domain}-{namespace}"[:63].rstrip("-")


def has_mutable_image(value: object) -> bool:
    if isinstance(value, dict):
        return any((key == "image" and isinstance(child, str) and "@sha256:" not in child)
                   or has_mutable_image(child) for key, child in value.items())
    if isinstance(value, list):
        return any(has_mutable_image(child) for child in value)
    return False


def role_rules(items: list[dict], state_name: str) -> list[dict]:
    rules: dict[tuple[str, str], set[str]] = defaultdict(set)
    for item in items:
        plural = PLURALS.get(item["kind"])
        if not plural:
            raise ValueError(f'no RBAC plural mapping for {item["apiVersion"]}/{item["kind"]}')
        rules[(group(item["apiVersion"]), plural)].add(item["metadata"]["name"])
    rules[("core", "configmaps")].add(state_name)
    return [
        {"apiGroups": ["" if api_group == "core" else api_group], "resources": [resource],
         "resourceNames": sorted(names), "verbs": ["get", "patch", "update", "delete"]}
        for (api_group, resource), names in sorted(rules.items())
    ]


def compile_outputs() -> dict[Path, str]:
    releases: dict[tuple[str, str], list[dict]] = defaultdict(list)
    legacy: list[dict] = []
    seen: dict[str, str] = {}
    for domain in DOMAINS:
        for item in docs(ROOT / f"clusters/re8ch/domains/{domain}/resources.yaml"):
            ident = identity(item)
            if ident in seen:
                raise ValueError(f"duplicate identity across {seen[ident]} and {domain}: {ident}")
            seen[ident] = domain
            meta = item.get("metadata", {})
            namespace = meta.get("namespace")
            if (not namespace or namespace == "flux-system" or item["kind"] in CLUSTER_KINDS |
                    FLUX_KINDS | {"Secret"} or has_mutable_image(item)):
                legacy.append(item)
            else:
                releases[(domain, namespace)].append(item)

    revision = "github-main-reviewed"
    files: dict[Path, str] = {}
    rbac_docs: list[dict] = []
    for (domain, namespace), items in sorted(releases.items()):
        items.sort(key=identity)
        name = release_name(domain, namespace)
        package = OUTPUT / name
        files[package / "resources.yaml"] = dump_all(items)
        files[package / "kustomization.yaml"] = yaml.safe_dump({
            "apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": ["resources.yaml"]
        }, sort_keys=False)
        inventory = sorted(identity(item) for item in items)
        contract = {
            "apiVersion": "delivery.re8ch.com/v1alpha1", "kind": "ReleaseContract", "metadata": {"name": name},
            "spec": {
                "target": {"cluster": "re8ch", "namespace": namespace},
                "source": {"renderer": "kustomize", "revision": revision, "repository": "re8ch/service-backend",
                           "path": str(package.relative_to(ROOT))},
                "provenance": {"repository": "re8ch/service-backend", "workflow": WORKFLOW,
                               "ref": "refs/heads/main", "environment": ENVIRONMENT, "audience": AUDIENCE,
                               "signer": f"https://github.com/re8ch/service-backend/{WORKFLOW}@refs/heads/main",
                               "issuer": "https://token.actions.githubusercontent.com"},
                "authorization": {"fieldManager": f"re8ch-release/{name}",
                                  "resources": sorted({f'{group(x["apiVersion"])}/{x["kind"]}' for x in items}),
                                  "objectNames": sorted({x["metadata"]["name"] for x in items}),
                                  "allowClusterScoped": False},
                "inventory": {"digest": digest(inventory)},
                "lifecycle": {"prune": True, "healthTimeoutSeconds": 300,
                              "protectedKinds": ["Namespace", "CustomResourceDefinition", "PersistentVolume",
                                                 "PersistentVolumeClaim", "StorageClass"],
                              "deletionAllowlist": [x for x in inventory if "/PersistentVolumeClaim/" not in x]},
            },
        }
        files[CONTRACTS / f"{name}.yaml"] = yaml.safe_dump(contract, sort_keys=False)
        state_name = state_configmap_name(name)
        rbac_docs.extend([
            {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": state_name, "namespace": namespace,
                "annotations": {"kustomize.toolkit.fluxcd.io/ssa": "Merge"},
                "labels": {"delivery.re8ch.com/state": "accepted", "delivery.re8ch.com/cohort": "main-domain"}}},
            {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "Role",
             "metadata": {"name": name, "namespace": namespace,
                          "labels": {"delivery.re8ch.com/rbac-profile": "main-domain"}},
             "rules": role_rules(items, state_name)},
            {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding",
             "metadata": {"name": name, "namespace": namespace,
                          "labels": {"delivery.re8ch.com/rbac-profile": "main-domain"}},
             "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "Role", "name": name},
             "subjects": [{"apiGroup": "rbac.authorization.k8s.io", "kind": "Group",
                           "name": "re8ch:release-executor:main-domain"}]},
        ])
    legacy.sort(key=identity)
    files[LEGACY / "resources.yaml"] = dump_all(legacy)
    files[LEGACY / "kustomization.yaml"] = yaml.safe_dump({
        "apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": ["resources.yaml"]
    }, sort_keys=False)
    files[RBAC] = dump_all(rbac_docs)
    manifest = {
        "apiVersion": "delivery.re8ch.com/main-domain-cohort/v1alpha1", "kind": "MainDomainSSACohort",
        "autonomousDomainsExcluded": sorted(AUTONOMOUS), "sourceDomains": list(DOMAINS),
        "releaseCount": len(releases), "objectCount": sum(map(len, releases.values())),
        "legacyObjectCount": len(legacy),
        "releases": [{"name": release_name(d, n), "domain": d, "namespace": n, "objects": len(items)}
                     for (d, n), items in sorted(releases.items())],
    }
    files[OUTPUT / "cohort.yaml"] = yaml.safe_dump(manifest, sort_keys=False)
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = compile_outputs()
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in expected.items()
                 if not path.is_file() or path.read_text() != content]
        if stale:
            raise SystemExit("stale main-domain SSA outputs:\n" + "\n".join(stale))
        return 0
    for directory in (OUTPUT, CONTRACTS, LEGACY):
        if directory.exists():
            shutil.rmtree(directory)
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
