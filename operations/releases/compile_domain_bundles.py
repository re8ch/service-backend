#!/usr/bin/env python3
"""Compile cross-tree domain manifests into Flux-local, reviewable bundles.

The authoring roots intentionally use Kustomize's unrestricted local loader so
they can compose existing reviewed manifests across this repository. Flux only
sees the generated bundle in each domain directory and therefore keeps its
normal root-only loader boundary at runtime.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
DOMAINS = ROOT / "clusters/re8ch/domains"
HEADER = "# Generated by operations/releases/compile_domain_bundles.py; do not edit.\n"


def render(source: Path) -> str:
    process = subprocess.run(
        [
            "kubectl",
            "kustomize",
            str(source),
            "--load-restrictor",
            "LoadRestrictionsNone",
        ],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return HEADER + process.stdout.rstrip() + "\n"


def domain_directories() -> list[Path]:
    return sorted(path.parent.parent for path in DOMAINS.glob("*/source/kustomization.yaml"))


def write_atomic(path: Path, content: str) -> None:
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if a checked-in bundle is stale")
    args = parser.parse_args()

    stale: list[str] = []
    for domain in domain_directories():
        output = domain / "resources.yaml"
        compiled = render(domain / "source")
        if args.check:
            if not output.is_file() or output.read_text(encoding="utf-8") != compiled:
                stale.append(str(output.relative_to(ROOT)))
        else:
            write_atomic(output, compiled)

    if stale:
        print("stale domain bundles:")
        print(*stale, sep="\n")
        print("run: python operations/releases/compile_domain_bundles.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
